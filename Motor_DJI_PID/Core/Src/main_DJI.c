void Motor_Init(void)
{
  float pos_pid_param[3] = { 10.0f, 0.0f, 0.0f };  // 位置环 P, I, D
  float spd_pid_param[3] = { 20.0f, 1.0f, 0.0f };  // 速度环 P, I, D

  for (int i = 0; i < 4; i++)
  {
    // 1. 绑定 PID 指针：必须绑到 pid_type 结构体对象，不能绑到 float 参数数组！
    Arm_Motor[i].PositionPID = &pos_pid_obj[i];
    Arm_Motor[i].SpeedPID    = &spd_pid_obj[i];

    // 2. 初始化 PID 参数 (调用 PID.c 里的函数)
    PID_Parameter_Init(Arm_Motor[i].PositionPID, PID_POSITION, pos_pid_param, 3000, 1000, 0);
    PID_Parameter_Init(Arm_Motor[i].SpeedPID,    PID_DELTA,    spd_pid_param, 16384, 10000, 0);

    // 3. 初始化电机硬件信息
    Arm_Motor[i].id = i + 1;             // CAN ID: 1~4，反馈帧 0x201~0x204
    Arm_Motor[i].CAN_ID = 1;             // 挂在 CAN1 上
    Arm_Motor[i].type = MOTOR_3508;       // DJIMotor_ParaHandle 按 type 解析反馈，必须设置
    Arm_Motor[i].Reductionratio = 19;    // 3508 减速比 19:1
    Arm_Motor[i].Out = 0;                // 初始电流设为 0
  }
}

void DJI_Send(void)
{
  static CanSend_Type CANSend;
    
  // 大疆 1~4 号电机控制 ID 为 0x200
  CANSend.CANx = Arm_Motor[0].CAN_ID; // 这里传入的是 1 (代表 CAN1)
  CANSend.stdid = 0x200; 

  // 打包 1 号电机 (数据来自 Arm_Motor[0].Out)
  CANSend.Data[0] = (uint8_t)(Arm_Motor[0].Out >> 8);
  CANSend.Data[1] = (uint8_t)(Arm_Motor[0].Out & 0xFF);
    
  // 打包 2 号电机 (如果没有，就填 0)
  CANSend.Data[2] = (uint8_t)(Arm_Motor[1].Out >> 8);
  CANSend.Data[3] = (uint8_t)(Arm_Motor[1].Out & 0xFF);
    
  // 打包 3 号电机
  CANSend.Data[4] = (uint8_t)(Arm_Motor[2].Out >> 8);
  CANSend.Data[5] = (uint8_t)(Arm_Motor[2].Out & 0xFF);
    
  // 打包 4 号电机
  CANSend.Data[6] = (uint8_t)(Arm_Motor[3].Out >> 8);
  CANSend.Data[7] = (uint8_t)(Arm_Motor[3].Out & 0xFF);

  // 塞进队列
  xQueueSend(Queue_CANSend, &CANSend, 3);
}

void Task_CAN_Transmit(void *argument)
{
  CanSend_Type txMsg;
  for(;;)
  {
    // 从队列中取数据，死等 (portMAX_DELAY)
    if (xQueueReceive(Queue_CANSend, &txMsg, portMAX_DELAY) == pdPASS)
    {
      // 配置 FDCAN 发送头：整体清零，避免栈上随机值污染未显式赋值的字段
      FDCAN_TxHeaderTypeDef TxHeader = {0};

      TxHeader.Identifier          = txMsg.stdid;
      TxHeader.IdType              = FDCAN_STANDARD_ID;
      TxHeader.TxFrameType         = FDCAN_DATA_FRAME;
      TxHeader.DataLength          = FDCAN_DLC_BYTES_8;
      TxHeader.ErrorStateIndicator = FDCAN_ESI_ACTIVE;
      TxHeader.BitRateSwitch       = FDCAN_BRS_OFF;    // 传统 CAN 不变速
      TxHeader.FDFormat            = FDCAN_CLASSIC_CAN;
      TxHeader.MessageMarker       = 0;
            
      HAL_FDCAN_AddMessageToTxFifoQ(&hfdcan1, &TxHeader, txMsg.Data);
    }
  }
}

void Task_Motor_Control(void *argument)
{
  TickType_t lastWakeTime = xTaskGetTickCount();
  for(;;)
  {
    #if SITUATION

    // 1. 设定目标角度
    Arm_Motor[0].TargetAngle = 180.0f;
    // 2. 位置环
    float target_speed = Pid_cal(Arm_Motor[0].PositionPID, Arm_Motor[0].TargetAngle, Arm_Motor[0].RealAngle);

    #else

    float target_speed = 300.0f;

    #endif

    //3.速度环
    float target_current = Pid_cal(Arm_Motor[0].SpeedPID, target_speed, Arm_Motor[0].Realrotationrate);
                                       
    Arm_Motor[0].Out = (int16_t)target_current;

    // 4. 打包发队列 
    DJI_Send(); // 注意在这个函数里调用 xQueueSend

    vTaskDelayUntil(&lastWakeTime, pdMS_TO_TICKS(1));
  }
}
